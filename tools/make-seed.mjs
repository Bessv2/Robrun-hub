#!/usr/bin/env node
// Build seed.sql from data/*.psv. Run with `npm run seed:build`; `npm run db:local` / `db:remote` do it for you.
//
// The seed is an upsert: it refreshes game data but never touches what the clan entered on the site
// (price overrides, model input values, members, status, progress, plan, raids).

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RARITY = ['', 'Common', 'Uncommon', 'Rare', 'Epic', 'Legendary', 'Exotic'];

export async function readPsv(file) {
  const text = await readFile(join(ROOT, file), 'utf8');
  const lines = text.split('\n').filter((l) => l.trim() && !l.startsWith('#'));
  const cols = lines.shift().split('|');
  return lines.map((line, n) => {
    const cells = line.split('|');
    if (cells.length !== cols.length) throw new Error(`${file}: row ${n + 1} has ${cells.length} cells, expected ${cols.length}`);
    return Object.fromEntries(cols.map((c, i) => [c, cells[i]]));
  });
}

const sql = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const num = (v) => (v === '' || v == null ? null : Number(v));

async function main() {
  const tree = await readPsv('data/larry-tree.psv');
  const products = await readPsv('data/products.psv');
  const inputs = await readPsv('data/model-inputs.psv');

  const items = [
    ...tree.map((r, i) => ({
      id: r.id, kind: 'node', name: r.name, category: r.category, tier: num(r.tier),
      rarity: RARITY[Number(r.rarity)] || null, requires: r.requires, research_cost: num(r.research_cost),
      price: num(r.price), price_source: 'laptop', smuggler: null, fence: null, hub_buy: null, seized: null,
      sentence_years: num(r.sentence_years), sort: i,
    })),
    ...products.map((r, i) => ({
      id: r.id, kind: 'product', name: r.name, category: r.group, tier: null, rarity: r.rarity || null,
      requires: '', research_cost: null, price: num(r[r.price_from]), price_source: r.price_from,
      smuggler: num(r.smuggler), fence: num(r.fence), hub_buy: num(r.hub_buy), seized: num(r.seized),
      sentence_years: null, sort: 1000 + i,
    })),
  ];
  const ids = new Set();
  for (const it of items) {
    if (ids.has(it.id)) throw new Error(`duplicate item id ${it.id}`);
    ids.add(it.id);
  }

  const cols = Object.keys(items[0]);
  const out = [
    '-- Generated by tools/make-seed.mjs from data/*.psv. Do not edit; do not commit.',
    'UPDATE items SET retired = 1;',
  ];
  for (const it of items) {
    out.push(
      `INSERT INTO items (${cols.join(', ')}, retired) VALUES (${cols.map((c) => sql(it[c])).join(', ')}, 0) ` +
        `ON CONFLICT(id) DO UPDATE SET ${cols.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(', ')}, retired = 0;`,
    );
  }
  for (const r of inputs) {
    out.push(
      `INSERT INTO model_inputs (key, business, label, value, unit, status, how_to_measure, sort) VALUES (` +
        [r.key, r.business, r.label, num(r.value), r.unit, r.status, r.how_to_measure, num(r.sort) ?? 0].map(sql).join(', ') +
        `) ON CONFLICT(key) DO UPDATE SET business = excluded.business, label = excluded.label, unit = excluded.unit, ` +
        `how_to_measure = excluded.how_to_measure, sort = excluded.sort;`,
    );
  }
  out.push(`DELETE FROM model_inputs WHERE key NOT IN (${inputs.map((r) => sql(r.key)).join(', ')});`);

  await writeFile(join(ROOT, 'seed.sql'), out.join('\n') + '\n');
  console.log(`seed.sql: ${tree.length} tree nodes, ${products.length} products, ${inputs.length} model inputs`);
}

if (import.meta.url === `file://${process.argv[1]}`) main().catch((e) => { console.error(e.message); process.exit(1); });
